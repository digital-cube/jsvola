type Equals<A, B> =
  (<T>() => T extends A ? 1 : 2) extends <T>() => T extends B ? 1 : 2 ? true : false;
type Resolved<T> = T extends Promise<infer U> ? U : never;
/** `true` only when `F` resolves with exactly `T`. */
type Returns<F extends (...args: never[]) => unknown, T> = Equals<Resolved<ReturnType<F>>, T>;

